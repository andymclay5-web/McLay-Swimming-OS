'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
const instant=read('engines/swimmer-instant-open-cn.js');
const evidence=read('engines/evidence.js');
const perf=read('engines/swimmer-performance-ci.js');
const exp=read('engines/swimmer-experience-cl.js');
const compact=read('engines/swimmer-performance-compact-cm.js');
const invite=read('engines/swimmer-invite-bn.js');
const portal=read('swimmer-portal.js');
assert.ok(instant.includes('quickRanked'),'coach swimmer open must use local quick ranking');
assert.ok(!instant.includes("setTimeout(()=>M.swimmerPerformanceBM?.completeEvidence"),'swimmer navigation must not launch cloud evidence completion');
assert.ok(instant.includes('Performance</button>')&&instant.includes('Training</button>')&&instant.includes('Tests</button>')&&instant.includes('Meet</button>'),'coach swimmer shell must stay simple');
assert.ok(instant.includes('Tap to load pathway, PB race and splits'),'coach event drill-down contract missing');
assert.ok(evidence.includes('sameAthleteWithIdentity')&&evidence.includes('ident=identityFor(ath,state)'),'athlete row filtering must reuse identity rather than rebuild it per row');
assert.ok(perf.includes('backgroundCompletionDisabled=true'),'background evidence completion must be disabled');
assert.ok(exp.includes('disabled:true'),'legacy swimmer experience layer must be retired');
assert.ok(compact.includes('disabled:true'),'duplicate compact renderer must be retired');
assert.ok(invite.includes("schema:'msos-swimmer-portal-v5'"),'secure portal payload must be session-capable v5');
assert.ok(invite.includes('session:safeSession(a)'),'secure portal must receive the current individual session');
assert.ok(invite.includes('tests:safeTests(a)')&&invite.includes('meet:safeMeet(a)'),'portal must receive swimmer-only tests and meet data');
assert.ok(!invite.includes('new MutationObserver'),'swimmer access must not add a mutation-observer render loop');
assert.ok(portal.includes("TAB='session'"),'swimmer portal must open on Session');
assert.ok(portal.includes('Strongest performance first.')&&portal.includes('Tap an event for the full pathway, PB race and splits.'),'Performance must stay event-led, not a giant expanded ladder');
assert.ok(portal.includes('data-tab="session"')&&portal.includes('data-tab="performance"')&&portal.includes('data-tab="training"')&&portal.includes('data-tab="tests"')&&portal.includes('data-tab="meet"'),'portal session/performance/training/tests/meet shell missing');
assert.ok(portal.includes('Challenge this set')&&portal.includes('Edit your version')&&portal.includes('Finish session'),'interactive session contract missing');
console.log('SWIMMER_SURFACE_CO_PASS');
