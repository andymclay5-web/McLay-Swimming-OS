'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
global.MSOS4={};
require('../engines/swimmer-experience-cl.js');
assert.equal(global.MSOS4.swimmerExperienceCL.build,'v4-swimmer-context-unified-20260824cl');
assert.equal(global.MSOS4.swimmerExperienceCL.disabled,true,'legacy swimmer experience UI must stay retired');
const exp=fs.readFileSync(path.join(root,'engines','swimmer-experience-cl.js'),'utf8');
const instant=fs.readFileSync(path.join(root,'engines','swimmer-instant-open-cn.js'),'utf8');
const evidence=fs.readFileSync(path.join(root,'engines','evidence.js'),'utf8');
const pwa=fs.readFileSync(path.join(root,'engines','pwa-update.js'),'utf8');
const storage=fs.readFileSync(path.join(root,'engines','storage.js'),'utf8');
assert.match(exp,/disabled:true/,'legacy swimmer layer must not install observers or click handlers');
assert.doesNotMatch(exp,/MutationObserver|document\.addEventListener\('click'/,'retired layer must not own runtime interaction');
assert.match(instant,/Performance<\/button>/,'unified surface must own Performance');
assert.match(instant,/Training<\/button>/,'unified surface must own Training');
assert.match(instant,/Tests<\/button>/,'unified surface must own individual Tests');
assert.match(instant,/Meet<\/button>/,'unified surface must own Meet');
assert.doesNotMatch(instant,/Pathway<\/button>/,'Pathway must expand inside Performance, not exist as another tab');
assert.match(instant,/quickRanked/,'unified surface must dedupe event rows for display');
assert.match(instant,/Tap to load pathway, PB race and splits/,'event detail must stay behind a tap');
assert.doesNotMatch(instant,/pathwaysForAthlete\?\./,'one event tap must not rebuild every athlete pathway');
assert.match(instant,/projectionFor\?\./,'Training tab must use the one-session athlete projection rather than scan all history');
for(const label of ['Energy systems','Stroke mix','Focus / makeup','Session makeup'])assert.ok(instant.includes(label),`Training surface must retain ${label}`);
assert.match(instant,/p\.zones/,'training must expose classified energy-system metres');
assert.match(instant,/p\.strokes/,'training must expose stroke metres');
assert.match(instant,/p\.tags/,'training must expose focus/makeup tags');
assert.match(instant,/p\.blocks/,'training must expose delivered session blocks');
assert.match(evidence,/sameAthleteWithIdentity/,'evidence matching must reuse one athlete identity per scan');
assert.match(storage,/loopAthleteTab:s\.loopAthleteTab/,'selected swimmer tab must persist across app resume');
assert.doesNotMatch(pwa,/else setTimeout\(\(\)=>P\.apply/,'background version checks must never force an app reload');
assert.doesNotMatch(pwa,/controllerchange[^\n]*P\.apply/,'service-worker controller changes must never force an app reload');
