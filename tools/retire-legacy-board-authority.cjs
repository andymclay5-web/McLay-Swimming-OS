'use strict';
const fs=require('node:fs');
const path=require('node:path');
const file=path.resolve(__dirname,'..','app.js');
let s=fs.readFileSync(file,'utf8');
const uiStart=s.indexOf('const UI=M.ui=M.ui||{};');
if(uiStart<0)throw new Error('UI core marker not found');
const boardStart=s.indexOf(' function composition(item){',uiStart);
const bindStart=s.indexOf(' UI.bindBoard=()=>{',boardStart);
const boardEndMarker='\n };\n})(globalThis);';
const boardEnd=s.indexOf(boardEndMarker,bindStart);
if(boardStart<0||bindStart<0||boardEnd<0)throw new Error('Legacy Board authority block markers not found');
s=s.slice(0,boardStart)+' // Board and TV rendering are owned exclusively by engines/board.js.\n'+s.slice(boardEnd+4);
const tvStart=s.indexOf(' UI.renderTV=()=>{');
if(tvStart<0)throw new Error('Legacy TV authority marker not found');
const tvEnd=s.indexOf('\n',tvStart);
s=s.slice(0,tvStart)+' // TV rendering is owned exclusively by engines/board.js.'+s.slice(tvEnd);
if(/UI\.renderBoard\s*=/.test(s))throw new Error('Legacy Board authority still present');
if(/UI\.renderTV\s*=/.test(s))throw new Error('Legacy TV authority still present');
fs.writeFileSync(file,s);
console.log('Retired legacy Board/TV runtime authority from app.js');
